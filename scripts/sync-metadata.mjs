/**
 * Single source of truth propagator.
 *
 * metadata/product.json holds the ONE authoritative version + product facts.
 * This script pushes that version into every place that would otherwise drift
 * (Cargo workspace, package.json, tauri.conf.json) and regenerates the typed
 * data the website consumes (client/src/generated/product.ts) from the
 * product/features/platforms metadata.
 *
 * Usage:
 *   node scripts/sync-metadata.mjs          # write everything
 *   node scripts/sync-metadata.mjs --check  # verify only, exit 1 on drift
 *
 * Release-time download truth (which artifact really exists) is a SEPARATE
 * generator: scripts/generate-site-releases.mjs, driven by real GitHub assets.
 */
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const check = process.argv.includes('--check');
const read = (rel) => fs.readFileSync(path.join(root, rel), 'utf8');
const readJson = (rel) => JSON.parse(read(rel));

const product = readJson('metadata/product.json');
const features = readJson('metadata/features.json');
const platforms = readJson('metadata/platforms.json');
const version = product.version;
if (!/^\d+\.\d+\.\d+$/.test(version)) {
  console.error(`metadata/product.json version is not semver: "${version}"`);
  process.exit(2);
}

const problems = [];
const writes = [];

// --- package.json ---------------------------------------------------------
{
  const rel = 'package.json';
  const pkg = readJson(rel);
  if (pkg.version !== version) {
    problems.push(`package.json version ${pkg.version} != ${version}`);
    pkg.version = version;
    writes.push([rel, `${JSON.stringify(pkg, null, 2)}\n`]);
  }
}

// --- Cargo.toml [workspace.package] version -------------------------------
{
  const rel = 'Cargo.toml';
  const text = read(rel);
  const updated = text.replace(
    /(\[workspace\.package\][^[]*?\bversion\s*=\s*")([^"]*)(")/,
    (_m, pre, cur, post) => {
      if (cur !== version) problems.push(`Cargo.toml workspace version ${cur} != ${version}`);
      return `${pre}${version}${post}`;
    },
  );
  if (updated !== text) writes.push([rel, updated]);
}

// --- tauri.conf.json version ----------------------------------------------
{
  const rel = 'desktop/src-tauri/tauri.conf.json';
  const conf = readJson(rel);
  if (conf.version !== version) {
    problems.push(`tauri.conf.json version ${conf.version} != ${version}`);
    conf.version = version;
    writes.push([rel, `${JSON.stringify(conf, null, 2)}\n`]);
  }
}

// --- generated site data (client/src/generated/product.ts) ----------------
{
  const rel = 'client/src/generated/product.ts';
  const abs = path.join(root, rel);
  const body = `/**
 * GENERATED by scripts/sync-metadata.mjs from metadata/*.json — do not hand-edit.
 * Authoritative product facts (version, tagline, features, platforms) consumed
 * by the public website so it never drifts from the repository.
 */
export type LocalizedText = { en: string; ru: string; tk: string };
export type FeatureStatus = "stable" | "beta" | "experimental" | "planned" | "deprecated" | "removed";
export type Feature = {
  id: string;
  category: string;
  status: FeatureStatus;
  since: string;
  name: LocalizedText;
  description: LocalizedText;
};
export type Platform = {
  id: string;
  os: string;
  arch: string;
  minimum_os: string;
  artifacts: string[];
};
export type Product = {
  product: string;
  version: string;
  channel: string;
  repository: string;
  website: string;
  tagline: LocalizedText;
  summary: LocalizedText;
  minimum_requirements: { ram_mib: number; free_disk_mib: number; notes_en: string; notes_ru: string; notes_tk: string };
  security_contract: Record<string, boolean>;
};

export const product: Product = ${JSON.stringify(
    {
      product: product.product,
      version: product.version,
      channel: product.channel,
      repository: product.repository,
      website: product.website,
      tagline: product.tagline,
      summary: product.summary,
      minimum_requirements: product.minimum_requirements,
      security_contract: product.security_contract,
    },
    null,
    2,
  )};

export const features: Feature[] = ${JSON.stringify(features.features, null, 2)};

export const platforms: Platform[] = ${JSON.stringify(
    platforms.platforms.map(({ id, os, arch, minimum_os, artifacts }) => ({ id, os, arch, minimum_os, artifacts })),
    null,
    2,
  )};
`;
  // Compare line-ending-insensitively: on Windows git may check the file out
  // with CRLF, which must not read as "stale" against our LF-generated body.
  const lf = (s) => (s == null ? null : s.replace(/\r\n/g, '\n'));
  const current = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
  if (lf(current) !== body) {
    problems.push('client/src/generated/product.ts is stale');
    writes.push([rel, body]);
  }
}

if (check) {
  if (problems.length) {
    console.error('metadata drift detected:');
    for (const p of problems) console.error(`  - ${p}`);
    console.error('Run: node scripts/sync-metadata.mjs');
    process.exit(1);
  }
  console.log(`metadata in sync at v${version}.`);
  process.exit(0);
}

for (const [rel, content] of writes) {
  const abs = path.join(root, rel);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, content);
  console.log(`synced ${rel}`);
}
if (!writes.length) console.log(`already in sync at v${version}.`);
